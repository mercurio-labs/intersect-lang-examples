import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";

test("the parameter graph and live baseline comparison work in the production view", async ({ page }) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.locator(".diagram-node")).toHaveCount(4);
  await expect(page.locator(".diagram-edge")).toHaveCount(3);
  await page.getByText("Rcore equations", { exact: true }).click();
  const equationSource = await readFile("language/thermal.rcore", "utf8");
  await expect(page.locator("#equation-source")).toHaveText(equationSource);
  await page.getByText("Rcore equations", { exact: true }).click();
  await expect(page.locator("#reading")).toHaveText("42.0 °C");
  await expect(page.locator("#equilibrium")).toHaveText("44.0 °C");
  await expect(page.locator("#difference")).toHaveText("0.0 °C");
  await expect(page.locator("#target")).toHaveText("7.2 min");
  const power = page.getByRole("slider", { name: "Heater power" });
  await power.focus();
  await power.press("End");
  await expect(page.locator("#power-value")).toHaveText("250 W");
  await expect(page.locator("#reading")).toHaveText("65.9 °C");
  await expect(page.locator("#difference")).toHaveText("+23.9 °C");
  const time = page.getByRole("slider", { name: "Inspect time" });
  await time.focus();
  await time.press("Home");
  await expect(page.locator("#reading")).toHaveText("20.0 °C");
  await page.getByRole("button", { name: "Reset" }).click();
  await expect(page.locator("#reading")).toHaveText("42.0 °C");
  const lossShape = page.locator('[data-symbol="loss"] > .node-body');
  await page.getByRole("button", { name: "Fit diagram" }).click();
  await lossShape.dblclick({ position: { x: 20, y: 15 } });
  await expect(page.getByRole("slider", { name: "Heat loss" })).toBeFocused();
  await page.keyboard.press("End");
  await expect(page.locator("#target")).toHaveText("Unreachable");
  await expect(page.locator("#equilibrium")).toHaveText("28.0 °C");
  await page.getByLabel("Run profile").selectOption("analytic");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download traces" }).click();
  const report = JSON.parse(await readFile(await (await download).path(), "utf8"));
  expect(report.cases.map(({ case: entry }) => entry.id)).toEqual(["baseline", "current"]);
  const { trace, summary } = report.cases[1];
  expect(trace.header.format).toBe("intersect.run.trace.v1");
  expect(trace.header.model_digest).toBe(createHash("sha256").update(equationSource).digest("hex"));
  expect(trace.header.language_data.equations.language).toBe("Rcore");
  expect(trace.header.profile.language_profile).toMatch(/:analytic$/);
  expect(trace.entries.filter(({ kind }) => kind === "event_delivered")).toHaveLength(120);
  expect(summary.targetSeconds).toBeNull();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("img", { name: /Current and baseline temperature/ })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  expect(errors).toEqual([]);
});
