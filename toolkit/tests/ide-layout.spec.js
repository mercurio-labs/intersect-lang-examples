test('vertical dividers resize adjacent columns and keep model layout unchanged', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.goto('/');
  await expect(page.locator('#compile-status')).toContainText('Language compiled',{timeout:30000});
  const left = page.getByRole('separator', { name: 'Resize containment and class diagram' });
  const right = page.getByRole('separator', { name: 'Resize class diagram and properties' });
  const widths = () => page.evaluate(() => ['.structure-tree-panel', '.structure-diagram-panel', '.structure-properties-panel'].map(selector => document.querySelector(selector).getBoundingClientRect().width));
  const original = await widths();
  const model = await page.evaluate(() => ({ source: window.workbench.definitionModels.ecore.getValue(), layout: window.workbench.structure.getLayout() }));
  async function move(handle, dx) {
    const box = await handle.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, { steps: 5 }); await page.mouse.up();
  }
  await move(left, 100);
  let current = await widths();
  expect(current[0]).toBeCloseTo(original[0] + 100, 0);
  expect(current[1]).toBeCloseTo(original[1] - 100, 0);
  expect(current[2]).toBeCloseTo(original[2], 0);
  await move(right, -60);
  current = await widths();
  expect(current[2]).toBeCloseTo(original[2] + 60, 0);
  await right.press('ArrowRight');
  expect((await widths())[2]).toBeCloseTo(current[2] - 10, 0);
  const adjusted = await widths();
  await page.getByRole('tab', { name: 'Test', exact: true }).click();
  await page.getByRole('tab', { name: 'Define', exact: true }).click();
  expect(await widths()).toEqual(adjusted);
  await left.press('End');
  expect((await widths())[1]).toBeGreaterThanOrEqual(219);
  await left.press('Home');
  expect((await widths())[0]).toBe(140);
  await left.dblclick();
  current = await widths();
  current.forEach((width, index) => expect(width).toBeCloseTo(original[index], 0));
  expect(await page.evaluate(() => ({ source: window.workbench.definitionModels.ecore.getValue(), layout: window.workbench.structure.getLayout() }))).toEqual(model);
  await expect(page.locator('.structure-body')).not.toHaveClass(/is-resizing/);
});

